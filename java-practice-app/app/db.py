# ---- review queue (spaced repetition) ----
REVIEW_DAYS = [1, 3, 7, 21]  # gaps between reviews; finishing the last one graduates the question
DAY = 86400


def enqueue_review(user_id, level, day, qnum, delay_days: int = 1) -> None:
    """Add a question to the review queue, due after delay_days. Does nothing if it is already queued."""
    with connect() as c:
        _x(c, "INSERT INTO reviews (user_id, level, day, qnum, stage, due_at) VALUES (?, ?, ?, ?, 0, ?) "
              "ON CONFLICT DO NOTHING", (user_id, level, day, qnum, int(time.time()) + delay_days * DAY))


def due_reviews(user_id: int, limit: int = 50):
    with connect() as c:
        return _x(c, "SELECT level, day, qnum, stage, due_at FROM reviews WHERE user_id = ? AND due_at <= ? "
                     "ORDER BY due_at LIMIT ?", (user_id, int(time.time()), limit)).fetchall()


