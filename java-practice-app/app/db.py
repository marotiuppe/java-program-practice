def list_ideas(viewer_id=None, sort: str = "top", status: str = ""):
    """Ideas that are not hidden, each with `votes` and `voted` (did the viewer vote). status "" means all
    except done/declined, which are kept on their own tabs."""
    sql = ("SELECT i.id, i.title, i.body, i.status, i.created_at, i.user_id, "
           "(SELECT COUNT(*) FROM idea_votes v WHERE v.idea_id = i.id) AS votes, "
           "(SELECT COUNT(*) FROM idea_votes v WHERE v.idea_id = i.id AND v.user_id = ?) AS voted "
           "FROM ideas i WHERE i.status != 'hidden'")
    params = [viewer_id or 0]
    if status:
        sql += " AND i.status = ?"
        params.append(status)
    else:
        sql += " AND i.status NOT IN ('done', 'declined')"
    sql += " ORDER BY " + ("i.created_at DESC, i.id DESC" if sort == "new" else "votes DESC, i.created_at DESC, i.id DESC")
    sql += " LIMIT 200"
    with connect() as c:
        return [dict(r) for r in _x(c, sql, params).fetchall()]


