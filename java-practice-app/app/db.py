def log_event(user_id: int, name: str, meta: str = "", once: bool = False) -> bool:
    """Append a usage event. With once=True, skip it if this user already has the same name+meta.
    Returns True when a row was written. Never raises: logging must not break a request."""
    try:
        with connect() as c:
            if once and _x(c, "SELECT 1 FROM events WHERE user_id = ? AND name = ? AND meta = ?",
                           (user_id, name, meta)).fetchone():
                return False
            _x(c, "INSERT INTO events (user_id, name, meta, created_at) VALUES (?, ?, ?, ?)",
               (user_id, name, meta, int(time.time())))
            return True
    except Exception:
        return False


