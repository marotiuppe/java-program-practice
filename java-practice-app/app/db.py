# Columns added after the first release. Each is applied only when missing, so old databases upgrade in place.
MIGRATIONS = [
    ("users", "daily_goal", "INTEGER NOT NULL DEFAULT 1"),
    ("users", "email_verified", "INTEGER NOT NULL DEFAULT 1"),
    ("users", "reminders", "INTEGER NOT NULL DEFAULT 0"),
    ("users", "tz", "TEXT NOT NULL DEFAULT ''"),
    ("progress", "solved_at", "BIGINT"),
]


def _migrate(c) -> None:
    for table, column, ddl in MIGRATIONS:
        if PG:
            c.execute(f"ALTER TABLE {table} ADD COLUMN IF NOT EXISTS {column} {ddl}")
        else:
            cols = {r["name"] for r in c.execute(f"PRAGMA table_info({table})").fetchall()}
            if column not in cols:
                c.execute(f"ALTER TABLE {table} ADD COLUMN {column} {ddl}")
    # Rows solved before solved_at existed: use their last update time as the best available estimate.
    c.execute("UPDATE progress SET solved_at = updated_at WHERE status = 'solved' AND solved_at IS NULL")


def init() -> None:
    if PG:
        with connect() as c:
            for stmt in SCHEMA_PG:
                c.execute(stmt)
            _migrate(c)
        return
    os.makedirs(os.path.dirname(os.path.abspath(DB_PATH)), exist_ok=True)
    with connect() as c:
        c.executescript(SCHEMA)
        _migrate(c)


def _x(c, sql, params=()):
    """Run a query written with '?' placeholders on either backend."""
    return c.execute(sql.replace("?", "%s") if PG else sql, params)


@contextmanager
def connect():
    if PG:
        conn = psycopg.connect(DATABASE_URL, row_factory=dict_row, connect_timeout=15)
    else:
        conn = sqlite3.connect(DB_PATH, timeout=10)
        conn.row_factory = sqlite3.Row
        conn.execute("PRAGMA journal_mode=WAL")
    try:
        yield conn
        conn.commit()
    finally:
        conn.close()


def hash_password(password: str) -> str:
    salt = secrets.token_bytes(16)
    digest = hashlib.scrypt(password.encode(), salt=salt, n=2**14, r=8, p=1)
    return f"scrypt${salt.hex()}${digest.hex()}"


def verify_password(password: str, stored: str) -> bool:
    try:
        _, salt_hex, digest_hex = stored.split("$")
        digest = hashlib.scrypt(password.encode(), salt=bytes.fromhex(salt_hex), n=2**14, r=8, p=1)
        return hmac.compare_digest(digest.hex(), digest_hex)
    except Exception:
        return False


def create_user(email: str, password: str, verified: bool = True):
    try:
        with connect() as c:
            cur = _x(
                c,
                "INSERT INTO users (email, pw_hash, created_at, email_verified) VALUES (?, ?, ?, ?)"
                + (" RETURNING id" if PG else ""),
                (email, hash_password(password), int(time.time()), 1 if verified else 0),
            )
            return cur.fetchone()["id"] if PG else cur.lastrowid
    except IntegrityError:
        return None


