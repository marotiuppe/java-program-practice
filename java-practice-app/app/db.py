def init() -> None:
    if PG:
        with connect() as c:
            for stmt in SCHEMA_PG:
                c.execute(stmt)
        return
    os.makedirs(os.path.dirname(os.path.abspath(DB_PATH)), exist_ok=True)
    with connect() as c:
        c.executescript(SCHEMA)


def _x(c, sql, params=()):
    """Run a query written with '?' placeholders on either backend."""
    return c.execute(sql.replace("?", "%s") if PG else sql, params)


@contextmanager
def connect():
    if PG:
        conn = psycopg.connect(DATABASE_URL, row_factory=dict_row, connect_timeout=15)
    else:
        conn = sqlite3.connect(DB_PATH, timeout=10)
        conn.row_factory = sqlite3.Row
        conn.execute("PRAGMA journal_mode=WAL")
    try:
        yield conn
        conn.commit()
    finally:
        conn.close()


def hash_password(password: str) -> str:
    salt = secrets.token_bytes(16)
    digest = hashlib.scrypt(password.encode(), salt=salt, n=2**14, r=8, p=1)
    return f"scrypt${salt.hex()}${digest.hex()}"


def verify_password(password: str, stored: str) -> bool:
    try:
        _, salt_hex, digest_hex = stored.split("$")
        digest = hashlib.scrypt(password.encode(), salt=bytes.fromhex(salt_hex), n=2**14, r=8, p=1)
        return hmac.compare_digest(digest.hex(), digest_hex)
    except Exception:
        return False


def create_user(email: str, password: str):
    try:
        with connect() as c:
            cur = _x(
                c,
                "INSERT INTO users (email, pw_hash, created_at) VALUES (?, ?, ?)" + (" RETURNING id" if PG else ""),
                (email, hash_password(password), int(time.time())),
            )
            return cur.fetchone()["id"] if PG else cur.lastrowid
    except IntegrityError:
        return None


def get_user_by_email(email: str):
    with connect() as c:
        return _x(c, "SELECT * FROM users WHERE email = ?", (email,)).fetchone()


def get_user(user_id: int):
    with connect() as c:
        return _x(c, "SELECT * FROM users WHERE id = ?", (user_id,)).fetchone()


def set_level(user_id: int, level: str) -> None:
    with connect() as c:
        _x(c, "UPDATE users SET level = ? WHERE id = ?", (level, user_id))


def get_progress(user_id: int, level: str):
    with connect() as c:
        return _x(c,
            "SELECT day, qnum, status FROM progress WHERE user_id = ? AND level = ?",
            (user_id, level),
        ).fetchall()


def get_question_progress(user_id: int, level: str, day: int, qnum: int):
    with connect() as c:
        return _x(c,
            "SELECT status, code, attempts FROM progress "
            "WHERE user_id = ? AND level = ? AND day = ? AND qnum = ?",
            (user_id, level, day, qnum),
        ).fetchone()


def save_progress(user_id, level, day, qnum, code, status, count_attempt):
    """Upsert. A status of None keeps the current one (default 'attempted' once code is saved)."""
    now = int(time.time())
    with connect() as c:
        row = _x(c,
            "SELECT status, attempts FROM progress "
            "WHERE user_id = ? AND level = ? AND day = ? AND qnum = ?",
            (user_id, level, day, qnum),
        ).fetchone()
        if row is None:
            _x(c,
                "INSERT INTO progress (user_id, level, day, qnum, status, code, attempts, updated_at) "
                "VALUES (?, ?, ?, ?, ?, ?, ?, ?)",
                (user_id, level, day, qnum, status or "attempted", code, 1 if count_attempt else 0, now),
            )
        else:
            new_status = status or ("attempted" if row["status"] == "todo" else row["status"])
            _x(c,
                "UPDATE progress SET status = ?, code = ?, attempts = attempts + ?, updated_at = ? "
                "WHERE user_id = ? AND level = ? AND day = ? AND qnum = ?",
                (new_status, code, 1 if count_attempt else 0, now, user_id, level, day, qnum),
            )


_RANK = {"todo": 0, "attempted": 1, "solved": 2}


def set_status(user_id, level, day, qnum, status, count_attempt=True):
    """Raise the status (todo < attempted < solved) and count an attempt; never lowers it.
    The saved code is left untouched."""
    now = int(time.time())
    with connect() as c:
        row = _x(c,
            "SELECT status FROM progress WHERE user_id = ? AND level = ? AND day = ? AND qnum = ?",
            (user_id, level, day, qnum),
        ).fetchone()
        if row is None:
            _x(c,
                "INSERT INTO progress (user_id, level, day, qnum, status, code, attempts, updated_at) "
                "VALUES (?, ?, ?, ?, ?, '', ?, ?)",
                (user_id, level, day, qnum, status, 1 if count_attempt else 0, now),
            )
        else:
            new_status = status if _RANK[status] > _RANK[row["status"]] else row["status"]
            _x(c,
                "UPDATE progress SET status = ?, attempts = attempts + ?, updated_at = ? "
                "WHERE user_id = ? AND level = ? AND day = ? AND qnum = ?",
                (new_status, 1 if count_attempt else 0, now, user_id, level, day, qnum),
            )


def touch_activity(user_id: int, date_str: str) -> None:
    """Record that the user practiced on this calendar date (YYYY-MM-DD in the app timezone)."""
    with connect() as c:
        _x(c, "INSERT INTO activity (user_id, day) VALUES (?, ?) ON CONFLICT DO NOTHING", (user_id, date_str))


def get_active_dates(user_id: int) -> list:
    with connect() as c:
        rows = _x(c, "SELECT day FROM activity WHERE user_id = ?", (user_id,)).fetchall()
    return [r["day"] for r in rows]


def log_event(user_id: int, name: str, meta: str = "", once: bool = False) -> bool:
    """Append a usage event. With once=True, skip it if this user already has the same name+meta.
    Returns True when a row was written. Never raises: logging must not break a request."""
    try:
        with connect() as c:
            if once and _x(c, "SELECT 1 FROM events WHERE user_id = ? AND name = ? AND meta = ?",
                           (user_id, name, meta)).fetchone():
                return False
            _x(c, "INSERT INTO events (user_id, name, meta, created_at) VALUES (?, ?, ?, ?)",
               (user_id, name, meta, int(time.time())))
            return True
    except Exception:
        return False


def count_solved_in_day(user_id: int, level: str, day: int) -> int:
    with connect() as c:
        return _x(c, "SELECT COUNT(*) AS n FROM progress WHERE user_id = ? AND level = ? AND day = ? "
                     "AND status = 'solved'", (user_id, level, day)).fetchone()["n"]


def add_report(user_id, level, day, qnum, category, note, code) -> None:
    with connect() as c:
        _x(c, "INSERT INTO reports (user_id, level, day, qnum, category, note, code, created_at) "
              "VALUES (?, ?, ?, ?, ?, ?, ?, ?)",
           (user_id, level, day, qnum, category, note, code, int(time.time())))


def admin_overview(today: str, week_start: str) -> dict:
    """Headline numbers for the admin page."""
    with connect() as c:
        one = lambda sql, p=(): _x(c, sql, p).fetchone()["n"]
        return {
            "users": one("SELECT COUNT(*) AS n FROM users"),
            "dau": one("SELECT COUNT(*) AS n FROM activity WHERE day = ?", (today,)),
            "wau": one("SELECT COUNT(DISTINCT user_id) AS n FROM activity WHERE day >= ?", (week_start,)),
            "solves": one("SELECT COUNT(*) AS n FROM progress WHERE status = 'solved'"),
            "open_reports": one("SELECT COUNT(*) AS n FROM reports WHERE resolved = 0"),
            "events": {r["name"]: r["n"] for r in _x(
                c, "SELECT name, COUNT(*) AS n FROM events GROUP BY name ORDER BY n DESC").fetchall()},
        }


def list_reports(include_resolved: bool = False, limit: int = 100):
    with connect() as c:
        where = "" if include_resolved else "WHERE r.resolved = 0 "
        return _x(c, "SELECT r.*, u.email FROM reports r LEFT JOIN users u ON u.id = r.user_id "
                     f"{where}ORDER BY r.id DESC LIMIT ?", (limit,)).fetchall()


def resolve_report(report_id: int) -> None:
    with connect() as c:
        _x(c, "UPDATE reports SET resolved = 1 WHERE id = ?", (report_id,))


def hardest_questions(limit: int = 15, min_users: int = 2):
    """Questions with the most attempts per learner and the lowest solve rate."""
    with connect() as c:
        return _x(c, "SELECT level, day, qnum, COUNT(*) AS users, SUM(attempts) AS attempts, "
                     "SUM(CASE WHEN status = 'solved' THEN 1 ELSE 0 END) AS solved "
                     "FROM progress GROUP BY level, day, qnum HAVING COUNT(*) >= ? "
                     "ORDER BY (1.0 * SUM(CASE WHEN status = 'solved' THEN 1 ELSE 0 END) / COUNT(*)) ASC, "
                     "SUM(attempts) DESC LIMIT ?", (min_users, limit)).fetchall()
