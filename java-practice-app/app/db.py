def toggle_vote(idea_id: int, user_id: int) -> bool:
    """Vote, or take the vote back. Returns True when the user now has a vote on the idea."""
    with connect() as c:
        had = _x(c, "SELECT 1 FROM idea_votes WHERE idea_id = ? AND user_id = ?", (idea_id, user_id)).fetchone()
        if had:
            _x(c, "DELETE FROM idea_votes WHERE idea_id = ? AND user_id = ?", (idea_id, user_id))
            return False
        _x(c, "INSERT INTO idea_votes (idea_id, user_id, created_at) VALUES (?, ?, ?)",
           (idea_id, user_id, int(time.time())))
        return True


