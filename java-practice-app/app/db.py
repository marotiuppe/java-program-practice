def _migrate(c) -> None:
    for table, column, ddl in MIGRATIONS:
        if PG:
            c.execute(f"ALTER TABLE {table} ADD COLUMN IF NOT EXISTS {column} {ddl}")
        else:
            cols = {r["name"] for r in c.execute(f"PRAGMA table_info({table})").fetchall()}
            if column not in cols:
                c.execute(f"ALTER TABLE {table} ADD COLUMN {column} {ddl}")
    # Rows solved before solved_at existed: use their last update time as the best available estimate.
    c.execute("UPDATE progress SET solved_at = updated_at WHERE status = 'solved' AND solved_at IS NULL")
    # a public profile handle belongs to one learner (empty means "none chosen")
    c.execute("CREATE UNIQUE INDEX IF NOT EXISTS users_handle_idx ON users (handle) WHERE handle != ''")


def init() -> None:
    if PG:
        with connect() as c:
            for stmt in SCHEMA_PG:
                c.execute(stmt)
            _migrate(c)
        return
    os.makedirs(os.path.dirname(os.path.abspath(DB_PATH)), exist_ok=True)
    with connect() as c:
        c.executescript(SCHEMA)
        _migrate(c)


def _x(c, sql, params=()):
    """Run a query written with '?' placeholders on either backend."""
    return c.execute(sql.replace("?", "%s") if PG else sql, params)


_pool = None


def _get_pool():
    """Shared Postgres connection pool. Opening a connection to a remote database (TLS + auth) takes hundreds of
    milliseconds, and a single page runs many queries, so connections are reused instead of opened per query."""
    global _pool
    if _pool is None:
        from psycopg_pool import ConnectionPool

        _pool = ConnectionPool(
            DATABASE_URL,
            min_size=1,
            max_size=int(os.environ.get("DB_POOL_MAX", "8")),
            max_idle=240,  # drop connections the host (e.g. Neon) would close anyway
            timeout=30,
            check=ConnectionPool.check_connection,  # replace a connection that went stale while idle
            kwargs={"row_factory": dict_row, "connect_timeout": 15},
            open=True,
        )
    return _pool


@contextmanager
def connect():
    if PG:
        # commits when the block ends normally, rolls back on an exception, then returns the connection
        with _get_pool().connection() as conn:
            yield conn
        return
    conn = sqlite3.connect(DB_PATH, timeout=10)
    conn.row_factory = sqlite3.Row
    conn.execute("PRAGMA journal_mode=WAL")
    try:
        yield conn
        conn.commit()
    finally:
        conn.close()


def hash_password(password: str) -> str:
    salt = secrets.token_bytes(16)
    digest = hashlib.scrypt(password.encode(), salt=salt, n=2**14, r=8, p=1)
    return f"scrypt${salt.hex()}${digest.hex()}"


def verify_password(password: str, stored: str) -> bool:
    try:
        _, salt_hex, digest_hex = stored.split("$")
        digest = hashlib.scrypt(password.encode(), salt=bytes.fromhex(salt_hex), n=2**14, r=8, p=1)
        return hmac.compare_digest(digest.hex(), digest_hex)
    except Exception:
        return False


def create_user(email: str, password: str, verified: bool = True, display_name: str = "", referred_by=None):
    try:
        with connect() as c:
            cur = _x(
                c,
                "INSERT INTO users (email, pw_hash, created_at, email_verified, display_name, referred_by) "
                "VALUES (?, ?, ?, ?, ?, ?)" + (" RETURNING id" if PG else ""),
                (email, hash_password(password), int(time.time()), 1 if verified else 0, display_name, referred_by),
            )
            return cur.fetchone()["id"] if PG else cur.lastrowid
    except IntegrityError:
        return None


