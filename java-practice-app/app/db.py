# rating -> how many stages to move: Forgot restarts, Hard repeats the gap, Good/Easy move on
RATING_STEP = {"forgot": None, "hard": 0, "good": 1, "easy": 2}


def rate_review(user_id, level, day, qnum, rating: str):
    """Reschedule (or graduate) a queued question. Returns 'graduated', 'scheduled' or None if not queued."""
    row = get_review(user_id, level, day, qnum)
    if row is None or rating not in RATING_STEP:
        return None
    step = RATING_STEP[rating]
    stage = 0 if step is None else row["stage"] + step
    with connect() as c:
        if stage >= len(REVIEW_DAYS):
            _x(c, "DELETE FROM reviews WHERE user_id = ? AND level = ? AND day = ? AND qnum = ?",
               (user_id, level, day, qnum))
            return "graduated"
        _x(c, "UPDATE reviews SET stage = ?, due_at = ? WHERE user_id = ? AND level = ? AND day = ? AND qnum = ?",
           (stage, int(time.time()) + REVIEW_DAYS[stage] * DAY, user_id, level, day, qnum))
        return "scheduled"


