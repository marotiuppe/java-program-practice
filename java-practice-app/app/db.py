def _token_hash(raw: str) -> str:
    return hashlib.sha256(raw.encode()).hexdigest()


def create_token(user_id: int, purpose: str, ttl_seconds: int) -> str:
    """Issue a single-use token (only its hash is stored). Earlier unused tokens of the same purpose stop working."""
    raw = secrets.token_urlsafe(32)
    now = int(time.time())
    with connect() as c:
        _x(c, "UPDATE auth_tokens SET used_at = ? WHERE user_id = ? AND purpose = ? AND used_at IS NULL",
           (now, user_id, purpose))
        _x(c, "INSERT INTO auth_tokens (token_hash, user_id, purpose, expires_at) VALUES (?, ?, ?, ?)",
           (_token_hash(raw), user_id, purpose, now + ttl_seconds))
    return raw


def peek_token(raw: str, purpose: str):
    """user_id if the token is valid right now (not used, not expired); does not use it up."""
    with connect() as c:
        row = _x(c, "SELECT user_id FROM auth_tokens WHERE token_hash = ? AND purpose = ? "
                    "AND used_at IS NULL AND expires_at > ?", (_token_hash(raw), purpose, int(time.time()))).fetchone()
    return row["user_id"] if row else None


def consume_token(raw: str, purpose: str):
    """Use the token up. Returns the user_id, or None if it was invalid, expired or already used."""
    now = int(time.time())
    with connect() as c:
        cur = _x(c, "UPDATE auth_tokens SET used_at = ? WHERE token_hash = ? AND purpose = ? "
                    "AND used_at IS NULL AND expires_at > ?", (now, _token_hash(raw), purpose, now))
        if cur.rowcount != 1:
            return None
        return _x(c, "SELECT user_id FROM auth_tokens WHERE token_hash = ?", (_token_hash(raw),)).fetchone()["user_id"]


# ---- privacy: export and delete everything we hold about a user ----
USER_TABLES = ["progress", "activity", "events", "reviews", "reports", "auth_tokens"]


def export_user(user_id: int) -> dict:
    """Everything stored for this user, as plain data (password hash and tokens are left out)."""
    with connect() as c:
        def rows(sql):
            return [dict(r) for r in _x(c, sql, (user_id,)).fetchall()]
        user = _x(c, "SELECT email, level, daily_goal, email_verified, created_at FROM users WHERE id = ?",
                  (user_id,)).fetchone()
        return {
            "account": dict(user) if user else None,
            "progress": rows("SELECT level, day, qnum, status, code, attempts, updated_at, solved_at FROM progress "
                             "WHERE user_id = ? ORDER BY level, day, qnum"),
            "active_days": [r["day"] for r in rows("SELECT day FROM activity WHERE user_id = ? ORDER BY day")],
            "events": rows("SELECT name, meta, created_at FROM events WHERE user_id = ? ORDER BY id"),
            "reviews": rows("SELECT level, day, qnum, stage, due_at FROM reviews WHERE user_id = ?"),
            "reports": rows("SELECT level, day, qnum, category, note, code, resolved, created_at FROM reports "
                            "WHERE user_id = ? ORDER BY id"),
        }


def delete_user(user_id: int) -> None:
    """Permanently remove the account and all of its data."""
    with connect() as c:
        for table in USER_TABLES:
            _x(c, f"DELETE FROM {table} WHERE user_id = ?", (user_id,))
        _x(c, "DELETE FROM users WHERE id = ?", (user_id,))


